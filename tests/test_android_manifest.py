"""Tests for the Android manifest hardening in mobile/app/tool."""
from __future__ import annotations

import importlib.util
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

TOOL = Path(__file__).resolve().parents[1] / "mobile" / "app" / "tool"
_spec = importlib.util.spec_from_file_location("manifest_tool", TOOL / "configure-android-manifest.py")
manifest_tool = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(manifest_tool)

ANDROID = "{http://schemas.android.com/apk/res/android}"

# src/main/AndroidManifest.xml as generated by `flutter create` (stable template).
FLUTTER_TEMPLATE = """<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <application
        android:label="kassensturz_mobile"
        android:name="${applicationName}"
        android:icon="@mipmap/ic_launcher">
        <activity
            android:name=".MainActivity"
            android:exported="true"
            android:launchMode="singleTop">
            <intent-filter>
                <action android:name="android.intent.action.MAIN"/>
                <category android:name="android.intent.category.LAUNCHER"/>
            </intent-filter>
        </activity>
        <meta-data
            android:name="flutterEmbedding"
            android:value="2" />
    </application>
    <queries>
        <intent>
            <action android:name="android.intent.action.PROCESS_TEXT"/>
            <data android:mimeType="text/plain"/>
        </intent>
    </queries>
</manifest>
"""


def parsed(manifest: str):
    root = ET.fromstring(manifest)
    permissions = [node.get(f"{ANDROID}name") for node in root.findall("uses-permission")]
    return root, permissions, root.find("application")


def test_template_gets_internet_permission_and_backup_disabled():
    root, permissions, application = parsed(manifest_tool.harden(FLUTTER_TEMPLATE))
    assert permissions == ["android.permission.INTERNET"]
    assert application.get(f"{ANDROID}allowBackup") == "false"
    assert application.get(f"{ANDROID}fullBackupContent") == "false"
    assert application.get(f"{ANDROID}dataExtractionRules") == "@xml/kassensturz_data_extraction_rules"
    # Nothing else of the template is lost.
    assert application.get(f"{ANDROID}icon") == "@mipmap/ic_launcher"
    assert application.find("activity").get(f"{ANDROID}name") == ".MainActivity"
    assert root.find("queries") is not None


def test_hardening_is_idempotent():
    once = manifest_tool.harden(FLUTTER_TEMPLATE)
    assert manifest_tool.harden(once) == once
    assert once.count("android.permission.INTERNET") == 1
    assert once.count("android:allowBackup") == 1


def test_existing_backup_setting_is_switched_off_and_permission_not_duplicated():
    manifest = FLUTTER_TEMPLATE.replace(
        "<application", '<uses-permission android:name="android.permission.INTERNET" />\n    <application', 1
    ).replace('android:label="kassensturz_mobile"', 'android:label="kassensturz_mobile"\n        android:allowBackup="true"')
    _, permissions, application = parsed(manifest_tool.harden(manifest))
    assert permissions == ["android.permission.INTERNET"]
    assert application.get(f"{ANDROID}allowBackup") == "false"


def test_camera_permission_from_other_tools_is_kept():
    manifest = FLUTTER_TEMPLATE.replace(
        "<application", '<uses-permission android:name="android.permission.CAMERA"/>\n    <application', 1
    )
    _, permissions, _ = parsed(manifest_tool.harden(manifest))
    assert sorted(permissions) == ["android.permission.CAMERA", "android.permission.INTERNET"]


@pytest.mark.parametrize("broken", ["<manifest></manifest>", FLUTTER_TEMPLATE + FLUTTER_TEMPLATE])
def test_unexpected_manifest_is_rejected(broken):
    with pytest.raises(manifest_tool.ManifestError):
        manifest_tool.harden(broken)


def test_script_rewrites_the_file_and_reports_missing_file(tmp_path):
    target = tmp_path / "AndroidManifest.xml"
    target.write_text(FLUTTER_TEMPLATE, encoding="utf-8")
    script = TOOL / "configure-android-manifest.py"
    done = subprocess.run([sys.executable, str(script), str(target)], capture_output=True, text=True)
    assert done.returncode == 0
    assert 'android:allowBackup="false"' in target.read_text(encoding="utf-8")
    rules = ET.parse(tmp_path / "res" / "xml" / "kassensturz_data_extraction_rules.xml").getroot()
    for section in ("cloud-backup", "device-transfer"):
        domains = {node.get("domain") for node in rules.find(section).findall("exclude")}
        assert domains == {"root", "file", "database", "sharedpref", "external"}
    missing = subprocess.run([sys.executable, str(script), str(tmp_path / "nope.xml")], capture_output=True, text=True)
    assert missing.returncode == 2


def test_bootstrap_script_runs_the_manifest_hardening():
    bootstrap = (TOOL / "bootstrap-platforms.sh").read_text(encoding="utf-8")
    assert "configure-android-manifest.py" in bootstrap
    assert bootstrap.index("flutter create") < bootstrap.index("configure-android-manifest.py")
